def main():
    made = 0
    for dirname, (desc, body) in SKILLS.items():
        skill_dir = os.path.join(ROOT, dirname)
        os.makedirs(skill_dir, exist_ok=True)
        # 官方规范：name 与目录名一致；description 1-1024 字符
        assert len(desc) <= 1024, f"{dirname} description 过长"
        assert dirname == dirname.lower() and all(c.isalnum() or c == "-" for c in dirname), f"{dirname} name 不合规"
        frontmatter = f"""---
name: {dirname}
description: {desc}
{COMMON_META}"""
        content = frontmatter + "\n---\n\n" + body + "\n"
        with open(os.path.join(skill_dir, "SKILL.md"), "w", encoding="utf-8") as f:
            f.write(content)
        made += 1
        print(f"  ✓ db/skills/{dirname}/SKILL.md（{len(desc)} 字符描述）")
    print(f"\n共重建 {made} 个技能（全部入 git 的产品资产，不受平台 skills/ 目录影响）")

if __name__ == "__main__":
    main()
